<?php

use Illuminate\Support\Facades\File;
use Studeo\Modular\Console\Actions\CreateModuleAction;
use Studeo\Modular\DataObjects\ModuleDefinition;
use Studeo\Modular\DataObjects\ModuleManifest;
use Studeo\Modular\Exceptions\InvalidModuleManifestException;
use Studeo\Modular\Support\ResolveModuleManifestAction;
use Studeo\Modular\Tests\TestCase;

uses(TestCase::class);

beforeEach(function () {
    $this->modulePath = config('modular.root_path').'/Account';
    File::deleteDirectory(config('modular.root_path'));
    File::ensureDirectoryExists(config('modular.root_path'));

    $this->module = new ModuleDefinition(
        name: 'Account',
        namespace: 'Studeo\\Account',
        path: $this->modulePath,
    );
});

afterEach(function () {
    File::deleteDirectory(config('modular.root_path'));
});

test('it resolves a valid module manifest', function () {
    $this->writeModuleManifest($this->modulePath, 'Account', 'Studeo\\Account');

    $manifest = app(ResolveModuleManifestAction::class)->execute($this->module);

    expect($manifest)->toBeInstanceOf(ModuleManifest::class)
        ->and($manifest->name)->toBe('Account')
        ->and($manifest->namespace)->toBe('Studeo\\Account');
});

test('it resolves the manifest generated by CreateModuleAction', function () {
    app(CreateModuleAction::class)->execute($this->module);

    $manifest = app(ResolveModuleManifestAction::class)->execute($this->module);

    expect($manifest->namespace)->toBe('Studeo\\Account');
});

test('the manifest namespace is authoritative over the configured namespace', function () {
    $this->writeModuleManifest($this->modulePath, 'Account', 'Legacy\\Account');

    $manifest = app(ResolveModuleManifestAction::class)->execute($this->module);

    expect($manifest->namespace)->toBe('Legacy\\Account')
        ->and($manifest->provider())->toBe('Legacy\\Account\\AccountServiceProvider');
});

test('it derives the provider and the three PSR-4 mappings from the namespace', function () {
    $manifest = new ModuleManifest('Account', 'Studeo\\Account');

    expect($manifest->provider())->toBe('Studeo\\Account\\AccountServiceProvider')
        ->and($manifest->psr4())->toBe([
            'Studeo\\Account\\' => '',
            'Studeo\\Account\\Database\\Factories\\' => 'database/factories/',
            'Studeo\\Account\\Database\\Seeders\\' => 'database/seeders/',
        ]);
});

test('it throws when module.json does not exist', function () {
    File::ensureDirectoryExists($this->modulePath);

    app(ResolveModuleManifestAction::class)->execute($this->module);
})->throws(InvalidModuleManifestException::class, 'Module manifest not found:');

test('it throws a loud legacy error that prints the module.json to create', function () {
    File::ensureDirectoryExists($this->modulePath);
    File::put($this->modulePath.'/composer.json', '{"name": "studeo/account"}');

    try {
        app(ResolveModuleManifestAction::class)->execute($this->module);
        $this->fail('InvalidModuleManifestException was not thrown');
    } catch (InvalidModuleManifestException $exception) {
        expect($exception->getMessage())
            ->toContain("Create {$this->modulePath}/module.json with:")
            ->toContain((new ModuleManifest('Account', 'Studeo\\Account'))->toJson());
    }
});

test('it throws when module.json contains invalid json', function () {
    $this->writeRawModuleManifest($this->modulePath, '{ invalid json }');

    app(ResolveModuleManifestAction::class)->execute($this->module);
})->throws(InvalidModuleManifestException::class, 'Invalid module manifest');

test('it throws when module.json does not decode to an object', function () {
    $this->writeRawModuleManifest($this->modulePath, '"just a string"');

    app(ResolveModuleManifestAction::class)->execute($this->module);
})->throws(InvalidModuleManifestException::class, 'expected a JSON object');

test('it throws when the name is missing', function () {
    $this->writeRawModuleManifest($this->modulePath, '{"namespace": "Studeo\\\\Account"}');

    app(ResolveModuleManifestAction::class)->execute($this->module);
})->throws(InvalidModuleManifestException::class, 'name must be the directory name [Account]');

test('it throws when the name does not match the directory name', function () {
    $this->writeModuleManifest($this->modulePath, 'Billing', 'Studeo\\Account');

    app(ResolveModuleManifestAction::class)->execute($this->module);
})->throws(InvalidModuleManifestException::class, 'name must be the directory name [Account]');

test('it throws when the namespace is missing', function () {
    $this->writeRawModuleManifest($this->modulePath, '{"name": "Account"}');

    app(ResolveModuleManifestAction::class)->execute($this->module);
})->throws(InvalidModuleManifestException::class, 'namespace must be a string');

test('it throws when the namespace has a trailing backslash', function () {
    $this->writeModuleManifest($this->modulePath, 'Account', 'Studeo\\Account\\');

    app(ResolveModuleManifestAction::class)->execute($this->module);
})->throws(InvalidModuleManifestException::class, 'must not end with a backslash');

test('it throws, naming the segment, when the namespace starts with one the root app owns', function (string $namespace, string $segment) {
    $this->writeModuleManifest($this->modulePath, 'Account', $namespace);

    expect(fn () => app(ResolveModuleManifestAction::class)->execute($this->module))
        ->toThrow(InvalidModuleManifestException::class, "starts with [{$segment}]");
})->with([
    'a vendor' => ['Illuminate\\Account', 'Illuminate'],
    'the app' => ['App\\Account', 'App'],
    'a prefix-less reserved name' => ['Database', 'Database'],
]);

test('it accepts a prefix-less manifest', function () {
    $this->writeModuleManifest($this->modulePath, 'Account', 'Account');

    expect(app(ResolveModuleManifestAction::class)->execute($this->module)->namespace)->toBe('Account');
});

test('it derives a kebab-case module key from the name', function () {
    expect((new ModuleManifest('Account', 'Studeo\\Account'))->key())->toBe('account')
        ->and((new ModuleManifest('BlogPosts', 'Studeo\\BlogPosts'))->key())->toBe('blog-posts')
        ->and(ModuleManifest::keyFor('BlogPosts'))->toBe('blog-posts');
});
